export type MsgKey = keyof typeof M;

function side(i: 0 | 1): { [K in MsgKey]: string } {
  const out = {} as { [K in MsgKey]: string };
  for (const k of Object.keys(M) as MsgKey[]) out[k] = M[k][i];
  return out;
}

/** `t("genel.title")`, `t("common.savedPath", { path })`. */
export const t = defineMessages(side(0), side(1));

/** Plural-aware lookup; `{n}` is filled in as a locale-formatted number. */
export function tn(n: number, one: MsgKey, other: MsgKey, vars: Vars = {}): string {
  return t(plural(n, one, other) as MsgKey, { n: new Intl.NumberFormat(locale()).format(n), ...vars });
}
