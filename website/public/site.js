const languageButton = document.querySelector("[data-language-toggle]");
const menuButton = document.querySelector(".menu-toggle");
const nav = document.querySelector(".nav-links");
let language = "tr";

function setLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translated = copy[language][element.dataset.i18n];
    if (translated) element.innerHTML = translated;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const translated = copy[language][element.dataset.i18nAria];
    if (translated) {
      element.setAttribute("aria-label", translated);
      element.setAttribute("title", translated);
    }
  });
  if (languageButton) {
    languageButton.textContent = language === "tr" ? "EN" : "TR";
    languageButton.setAttribute("aria-label", copy[language].langLabel);
  }
  if (nav) nav.classList.remove("is-open");
  if (menuButton) menuButton.setAttribute("aria-expanded", "false");
}

const owlCompanion = document.querySelector(".owl-companion");
const owlHead = owlCompanion?.querySelector(".owl-head");
const owlPupils = owlCompanion?.querySelectorAll("[data-owl-pupil]");

if (owlCompanion && owlHead && owlPupils?.length) {
  const motion = matchMedia("(prefers-reduced-motion: reduce)");
  window.addEventListener("pointermove", (event) => {
    if (motion.matches || (document.documentElement.dataset.mascotTheme ?? "owl") !== "owl") return;
    const bounds = owlCompanion.getBoundingClientRect();
    const centerX = bounds.left + bounds.width / 2;
    const centerY = bounds.top + bounds.height / 2;
    const horizontal = Math.max(-1, Math.min(1, (event.clientX - centerX) / (window.innerWidth * 0.38)));
    const vertical = Math.max(-1, Math.min(1, (event.clientY - centerY) / (window.innerHeight * 0.38)));
    owlHead.style.transform = `rotate(${horizontal * 10}deg) translateY(${vertical * 1.5}px)`;
    owlPupils.forEach((pupil) => {
      pupil.style.transform = `translate(${horizontal * 2.7}px, ${vertical * 2.4}px)`;
    });
  }, { passive: true });

  owlCompanion.addEventListener("click", () => {
    if (motion.matches || (document.documentElement.dataset.mascotTheme ?? "owl") !== "owl") return;
    owlCompanion.classList.remove("is-spinning");
    void owlCompanion.offsetWidth;
    owlCompanion.classList.add("is-spinning");
  });
  owlHead.addEventListener("animationend", () => owlCompanion.classList.remove("is-spinning"));
}

if (languageButton) languageButton.addEventListener("click", () => setLanguage(language === "tr" ? "en" : "tr"));
if (menuButton && nav) {
  menuButton.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("is-open");
    menuButton.setAttribute("aria-expanded", String(isOpen));
  });
  nav.addEventListener("click", (event) => {
    if (event.target instanceof HTMLAnchorElement) {
      nav.classList.remove("is-open");
      menuButton.setAttribute("aria-expanded", "false");
    }
  });
}
