// Renders the installers' pictures (src/baykus/installer-art.ts) from a running
// dev server with headless Edge or Chrome: the Windows installer's into
// src-tauri/nsis/art/ (plus frames.nsh, which unpacks them at install time),
// and the macOS disk image background into src-tauri/dmg/ (dmg.png, dmg@2x.png;
// scripts/dmg-background.mjs joins them into a Retina TIFF on a Mac).
//
//   npm run dev                       # terminal 1
//   node scripts/installer-art.mjs    # terminal 2
//
// Environment:
//   NOBETCI_URL    dev server (default http://127.0.0.1:1420)
//   NOBETCI_EDGE   path to Edge, Chrome or Chromium (default: Edge on Windows, google-chrome elsewhere)

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const out = join(root, "src-tauri", "nsis", "art");
const dmgOut = join(root, "src-tauri", "dmg");
const url = `${process.env.NOBETCI_URL ?? "http://127.0.0.1:1420"}/?demo=installer-art&lang=en&still=1`;
const browser =
  process.env.NOBETCI_EDGE ??
  (process.platform === "win32"
    ? "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe"
    : process.platform === "darwin"
      ? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
      : "google-chrome");

const dom = execFileSync(
  browser,
  [
    "--headless=new",
    "--disable-gpu",
    "--no-sandbox",
    "--hide-scrollbars",
    "--force-device-scale-factor=1",
    "--virtual-time-budget=15000",
    "--dump-dom",
    url,
  ],
  { encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] },
);
const match = /<pre id="art">([\s\S]*?)<\/pre>/.exec(dom);
if (!match) {
  console.error("No pictures on the page. Is the dev server running?");
  process.exit(1);
}
const art = JSON.parse(match[1].replaceAll("&quot;", '"').replaceAll("&amp;", "&"));

mkdirSync(out, { recursive: true });
mkdirSync(dmgOut, { recursive: true });
for (const f of readdirSync(out)) if (f.endsWith(".bmp")) rmSync(join(out, f));
let bytes = 0;
for (const [name, b64] of Object.entries(art)) {
  const buf = Buffer.from(b64, "base64");
  writeFileSync(join(name.endsWith(".png") ? dmgOut : out, name), buf);
  bytes += buf.length;
}

// NSIS needs every file named at compile time: one File line per frame, and
// the frame counts for the timer.
const names = Object.keys(art)
  .filter((n) => n.endsWith(".bmp"))
  .sort();
const count = (seq) => names.filter((n) => n.startsWith(`${seq}-`)).length;
const nsh = [
  "; Generated by scripts/installer-art.mjs — do not edit.",
  `!define NOBETCI_WAVE_FRAMES ${count("wave")}`,
  `!define NOBETCI_CHEER_FRAMES ${count("cheer")}`,
  "!macro NOBETCI_UNPACK_ART",
  ...names
    .filter((n) => /^(wave|cheer)-/.test(n))
    .map((n) => `  File "/oname=$PLUGINSDIR\\${n}" "\${NOBETCI_ART}\\${n}"`),
  "!macroend",
  "",
].join("\r\n");
writeFileSync(join(out, "frames.nsh"), `\uFEFF${nsh}`);
console.log(
  `Wrote ${Object.keys(art).length} pictures (${Math.round(bytes / 1024)} KB): src-tauri/nsis/art/ (with frames.nsh) and src-tauri/dmg/.`,
);
